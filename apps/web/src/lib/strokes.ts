/** 이 글자의 획순을 그릴 수 있는가. */
export function hasStrokes(letter: string): boolean {
  return letter in STROKES;
}

/** 획의 끝 방향(도). 화살촉을 어느 쪽으로 돌릴지 정한다. */
export function strokeAngle(stroke: Stroke): number {
  const end = stroke[stroke.length - 1]!;
  const before = stroke[stroke.length - 2] ?? end;
  return (Math.atan2(end[1] - before[1], end[0] - before[0]) * 180) / Math.PI;
}
