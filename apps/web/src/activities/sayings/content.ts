/**
 * 속담·사자성어 자료.
 *
 * **어느 표현을 넣을지는 제가 고르지 않았다.** 초등 교재 세 권의 목차를 모아
 * 겹치는 것을 센 결과다. 세 출판사가 따로 고른 표현이 겹쳤다는 것은 그만큼
 * 자주 쓰인다는 뜻이라, 그 겹친 횟수를 그대로 난이도 단계로 쓴다.
 *
 *   「하루 한장 속담」/「하루 한장 사자성어」 (미래엔, 각 100개)
 *   「바빠 초등 속담+따라 쓰기」/「… 사자성어+따라 쓰기」 (이지스에듀, 각 50개)
 *   「교과서랑 친해지는 하루 한 장 속담」/「… 사자성어」 (썬더키즈, 각 50개)
 *
 * 겹치는 것을 빼면 속담 137개, 사자성어 135개다. 여기 담은 것은 그중
 * **세 권 모두에 실린 24개**(속담 16 · 사자성어 8)로, 가장 먼저 알아야 할 것들이다.
 * 나머지는 차차 채운다. 조사 원본은
 * `docs/research/2026-09-09-속담-사자성어-교재-조사.md` 에 있다.
 *
 * 뜻풀이와 예문 문장은 책에서 가져온 것이 아니다 — 온라인에 공개돼 있지 않아
 * 표준국어대사전의 뜻을 아홉 살이 알아들을 말로 옮겨 적었다. 책을 사서
 * 대조하면 더 좋아진다.
 */

export type SayingKind = 'proverb' | 'idiom';

export interface Saying {
  /** 표현 그대로 */
  text: string;
  kind: SayingKind;
  /** 사자성어의 한자 */
  hanja?: string;
  /** 사자성어의 글자별 뜻. 3차 힌트에서 보여준다. */
  chars?: string[];
  /** 아홉 살이 알아들을 한 문장 */
  meaning: string;
  /** 아이 생활에서 나올 법한 짧은 예 */
  example: string;
  /**
   * 몇 권에 실렸는지(1~3). 3이 가장 흔하게 쓰이는 표현이다.
   * 이 숫자가 곧 단계가 된다.
   */
  books: 1 | 2 | 3;
  /**
   * 무엇에 관한 말인지. 그럴듯한 오답을 고르는 데 쓴다 —
   * 아무 뜻이나 섞으면 뜻을 몰라도 답이 보인다.
   */
  tag: string;
}

